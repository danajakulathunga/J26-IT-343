import 'dart:io' show File;
import 'package:flutter/foundation.dart';
import 'package:dio/dio.dart';
import 'package:path_provider/path_provider.dart';
import 'package:open_filex/open_filex.dart';
import 'package:share_plus/share_plus.dart';
import 'package:bananaguard_ai/core/api_client.dart';
import 'package:bananaguard_ai/core/storage/storage_service.dart';

import 'package:bananaguard_ai/services/download_helper.dart';

class ReportService {
  Future<String> downloadScanReport({
    required String scanId,
    Function(int received, int total)? onProgress,
  }) async {
    final guestName = storageService.getGuestName();
    final filename = 'BananaGuard_Report_${scanId.substring(0, 8)}.pdf';

    if (kIsWeb) {
      try {
        final response = await apiClient.dio.get<List<int>>(
          '/scans/$scanId/report',
          options: Options(
            headers: {
              if (guestName != null && guestName.isNotEmpty) 'X-Guest-Name': guestName,
            },
            responseType: ResponseType.bytes,
          ),
          onReceiveProgress: onProgress,
        );

        final bytes = Uint8List.fromList(response.data!);
        downloadBytes(bytes, filename);
        return filename;
      } on DioException catch (e) {
        if (e.response?.statusCode == 530) {
          throw Exception('Cloudflare Tunnel is inactive or expired (HTTP 530). Please restart tunnel or update Server URL in Settings.');
        }
        throw Exception(e.message ?? 'Server error downloading PDF report');
      }
    }

    final dir = await getApplicationDocumentsDirectory();
    final savePath = '${dir.path}/$filename';
    final targetFile = File(savePath);

    try {
      await apiClient.dio.download(
        '/scans/$scanId/report',
        savePath,
        options: Options(
          headers: {
            if (guestName != null && guestName.isNotEmpty) 'X-Guest-Name': guestName,
          },
          responseType: ResponseType.bytes,
        ),
        onReceiveProgress: onProgress,
      );

      return savePath;
    } on DioException catch (e) {
      // If server failed (e.g. 530 tunnel error) but user already had this report saved on disk:
      if (await targetFile.exists() && (await targetFile.length()) > 500) {
        debugPrint('⚠️ Network download failed, returning existing cached PDF report from disk');
        return savePath;
      }

      if (e.response?.statusCode == 530) {
        throw Exception(
          'Cloudflare Tunnel is inactive or expired (HTTP 530). '
          'Please ensure backend & tunnel are running, or update Server URL in Settings.',
        );
      } else if (e.response?.statusCode == 404) {
        throw Exception('Diagnostic scan or scan images not found on server (404).');
      } else if (e.type == DioExceptionType.connectionTimeout ||
          e.type == DioExceptionType.receiveTimeout) {
        throw Exception('Download timed out. Check your network connection.');
      } else if (e.type == DioExceptionType.connectionError) {
        throw Exception('Cannot reach backend server. Check Server URL in Settings.');
      }
      throw Exception(e.message ?? 'Failed to download report from server.');
    }
  }

  Future<void> openReport(String filePath) async {
    if (kIsWeb) {
      // On web the browser already handled downloading the file
      return;
    }

    try {
      await OpenFilex.open(filePath);
    } catch (_) {
      throw Exception('Could not open report file on device');
    }
  }

  Future<void> shareReport(String filePath) async {
    if (kIsWeb) return;

    try {
      await Share.shareXFiles(
        [XFile(filePath)],
        subject: 'BananaGuard AI Diagnostic Report',
        text: 'Banana diagnostic analysis report generated by BananaGuard AI.',
      );
    } catch (_) {
      throw Exception('Could not share report file');
    }
  }
}

final reportService = ReportService();
